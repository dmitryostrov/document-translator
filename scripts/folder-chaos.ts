const cost=Number(db(`select coalesce(sum(cost),0) from calls c join jobs j on j.id=c.job_id where j.group_id='${id}'`));assert.ok(cost<=maximum);
await writeFile("evidence/folder-chaos.json",JSON.stringify({group_id:id,children:3,completed:2,preflight_rejected:1,group_start_records:1,api_SIGKILL_after_first_child_start:true,completed_child_preserved:true,blocked_provider_calls:0,known_cost_usd:cost,approved_cap_usd:maximum,ownership_denied:true},null,2));
console.log(JSON.stringify({passed:true,evidence:"evidence/folder-chaos.json"}));
