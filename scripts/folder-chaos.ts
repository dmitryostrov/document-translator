await setup(process.env.SKIP_BUILD!=="1");const a=new Session(),b=new Session(),key=crypto.randomUUID(),f=new FormData();
for(const [name,text] of [["one.md",source],["two.md",source+" second"],["blocked.md","NATO RESTRICTED"]])f.append("file",new Blob([text]),name);
f.append("target_language","german");
const prepared=await a.request("/api/translation-groups",f,key);assert.equal(prepared.code,202);const id=prepared.data.group_id;
const g=await poll(async()=>(await a.request(`/api/translation-groups/${id}`)).data,g=>g.children.every((c:any)=>["AWAITING_APPROVAL","FAILED"].includes(c.stage)));
