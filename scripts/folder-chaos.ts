const good=g.children.filter((c:any)=>c.quote),blocked=g.children.find((c:any)=>!c.quote);
assert.equal((await a.start(good[0])).code,409);
assert.equal((await a.request(`/api/translation-groups/${id}/start`,JSON.stringify({quote_version:g.quote_version,max_total_cost_usd:.00001}),crypto.randomUUID())).code,409);
db("insert into test_gates(name,enabled,hits) values('group-child-started',true,0) on conflict(name) do update set enabled=true,hits=0");
const startKey=crypto.randomUUID(),body=JSON.stringify({quote_version:g.quote_version,max_total_cost_usd:maximum});
const pending=a.request(`/api/translation-groups/${id}/start`,body,startKey).catch(()=>null);
await poll(async()=>Number(db("select hits from test_gates where name='group-child-started'")),n=>n>0);
compose(["kill","-s","SIGKILL","api"]);await pending;db("update test_gates set enabled=false where name='group-child-started'");
const first=await poll(async()=>db(`select stage from jobs where id='${good[0].job_id}'`),s=>s==="SUCCEEDED");
const firstHash=db(`select artifact->>'hash' from jobs where id='${good[0].job_id}'`);
const firstCalls=db(`select count(*) from fake_events where job_id='${good[0].job_id}'`);
compose(["up","-d","--wait","api"]);
const raced=await Promise.all([a.request(`/api/translation-groups/${id}/start`,body,startKey),a.request(`/api/translation-groups/${id}/start`,body,startKey)]);
assert.ok(raced.every(r=>r.code===200));
for(const c of good)assert.equal((await a.done(c.job_id)).stage,"SUCCEEDED");
assert.equal(db(`select artifact->>'hash' from jobs where id='${good[0].job_id}'`),firstHash);
assert.equal(db(`select count(*) from fake_events where job_id='${good[0].job_id}'`),firstCalls);
assert.equal(db(`select count(*) from calls where job_id='${blocked.job_id}'`),"0");
assert.equal(db(`select count(*) from group_starts where group_id='${id}'`),"1");
